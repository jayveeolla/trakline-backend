const ExcelJS = require('exceljs')

const manilaDate = new Intl.DateTimeFormat('en-PH', { timeZone: 'Asia/Manila', dateStyle: 'long' })
const manilaTime = new Intl.DateTimeFormat('en-PH', { timeZone: 'Asia/Manila', hour: 'numeric', minute: '2-digit' })
const manilaStamp = new Intl.DateTimeFormat('en-PH', { timeZone: 'Asia/Manila', dateStyle: 'long', timeStyle: 'short' })

function dateValue(value) { return value ? manilaDate.format(new Date(value)) : '—' }
function timeValue(value) { return value ? manilaTime.format(new Date(value)) : '—' }

function uniqueSheetName(trip, used) {
  const base = String(trip.shuttle_code || trip.shuttle_id || 'Shuttle').replace(/[\\/*?:\[\]]/g, '-').slice(0, 25) || 'Shuttle'
  const departure = trip.started_at ? new Intl.DateTimeFormat('en-GB', { timeZone: 'Asia/Manila', hour: '2-digit', minute: '2-digit', hour12: false }).format(new Date(trip.started_at)).replace(':', '') : String(trip.id)
  let name = base.slice(0, 31)
  if (used.has(name.toLowerCase())) name = `${base.slice(0, 26)}-${departure}`.slice(0, 31)
  let suffix = 2
  while (used.has(name.toLowerCase())) name = `${base.slice(0, 26)}-${suffix++}`.slice(0, 31)
  used.add(name.toLowerCase())
  return name
}

function pngSize(buffer) {
  if (buffer.length < 24 || buffer.toString('hex', 0, 8) !== '89504e470d0a1a0a') return null
  return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) }
}

function signatureImage(data) {
  const match = /^data:image\/(png|jpeg|jpg);base64,([A-Za-z0-9+/=]+)$/.exec(String(data || ''))
  if (!match || match[2].length > 2_500_000) return null
  const buffer = Buffer.from(match[2], 'base64')
  if (!buffer.length) return null
  const extension = match[1] === 'png' ? 'png' : 'jpeg'
  const dimensions = extension === 'png' ? pngSize(buffer) : null
  const aspect = dimensions?.width && dimensions?.height ? dimensions.width / dimensions.height : 3
  const width = Math.min(148, 50 * aspect)
  const height = Math.min(50, width / aspect)
  return { buffer, extension, width, height }
}

function manifestSheet(workbook, trip, passengers, generatedBy, used) {
  const sheet = workbook.addWorksheet(uniqueSheetName(trip, used), {
    pageSetup: { paperSize: 9, orientation: 'landscape', fitToPage: true, fitToWidth: 1, fitToHeight: 0, margins: { left: 0.3, right: 0.3, top: 0.5, bottom: 0.5, header: 0.2, footer: 0.2 } },
    views: [{ state: 'frozen', ySplit: 13 }],
  })
  sheet.columns = [{ width: 7 }, { width: 12 }, { width: 19 }, { width: 29 }, { width: 23 }, { width: 17 }, { width: 26 }, { width: 18 }]
  sheet.mergeCells('A1:H1')
  sheet.getCell('A1').value = 'TDK PHILIPPINES CORPORATION'
  sheet.getCell('A1').font = { bold: true, color: { argb: 'FF123C70' }, size: 17 }
  sheet.getRow(1).height = 28
  sheet.mergeCells('A2:H2')
  sheet.getCell('A2').value = 'INCOMING SHUTTLE PASSENGER MANIFEST'
  sheet.getCell('A2').font = { bold: true, size: 13, color: { argb: 'FF0D6EFD' } }
  sheet.getRow(2).height = 25
  const details = [
    ['Date', dateValue(trip.trip_date), 'Shuttle', trip.shuttle_code || trip.shuttle_id],
    ['Trip ID', trip.trip_code, 'Route', trip.route_name || '—'],
    ['Driver', trip.driver_name || 'Unassigned', 'Departure', timeValue(trip.started_at)],
    ['Arrival / ETA', timeValue(trip.arrived_at_tdk || trip.eta_at_tdk), 'Status', trip.status],
    ['Capacity', Number(trip.capacity || 0), 'Passengers', passengers.length],
  ]
  details.forEach(([left, value, right, rightValue], i) => {
    const row = sheet.getRow(i + 4)
    row.getCell(1).value = left
    row.getCell(2).value = value
    row.getCell(5).value = right
    row.getCell(6).value = rightValue
    row.getCell(1).font = row.getCell(5).font = { bold: true, color: { argb: 'FF59708D' } }
    sheet.mergeCells(i + 4, 2, i + 4, 4)
    sheet.mergeCells(i + 4, 6, i + 4, 8)
  })
  sheet.mergeCells('A10:H10')
  sheet.getCell('A10').value = `Generated: ${manilaStamp.format(new Date())}    •    Generated By: Main Gate - ${generatedBy}`
  sheet.getCell('A10').font = { size: 9, italic: true, color: { argb: 'FF59708D' } }
  sheet.mergeCells('A12:H12')
  sheet.getCell('A12').value = 'PASSENGER MANIFEST'
  sheet.getCell('A12').font = { bold: true, size: 12, color: { argb: 'FF123C70' } }
  const headings = ['No.', 'Seat No.', 'Employee No.', 'Employee Name', 'Boarding Stop', 'Boarding Time', 'Signature', 'Verification']
  sheet.getRow(13).values = headings
  sheet.getRow(13).height = 25
  sheet.getRow(13).eachCell((cell) => {
    cell.font = { bold: true, color: { argb: 'FF123C70' } }
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFDCEBFF' } }
    cell.alignment = { vertical: 'middle', horizontal: 'center' }
    cell.border = { bottom: { style: 'thin', color: { argb: 'FF91B5E5' } } }
  })
  passengers.forEach((passenger, index) => {
    const rowNumber = index + 14
    const row = sheet.getRow(rowNumber)
    row.values = [index + 1, passenger.seat_number, passenger.employee_number, passenger.employee_name, passenger.boarding_stop_name || '—', timeValue(passenger.boarded_at), '', passenger.verification_status || 'PENDING']
    row.height = 48
    row.eachCell({ includeEmpty: true }, (cell) => {
      cell.alignment = { vertical: 'middle', horizontal: cell.col === 2 || cell.col === 1 || cell.col === 8 ? 'center' : 'left', wrapText: true }
      cell.border = { bottom: { style: 'hair', color: { argb: 'FFD4E2F0' } } }
      if (index % 2) cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF5F9FF' } }
    })
    const picture = signatureImage(passenger.signature_data)
    if (picture) {
      const imageId = workbook.addImage({ buffer: picture.buffer, extension: picture.extension })
      sheet.addImage(imageId, { tl: { col: 6 + Math.max(0, (160 - picture.width) / 14) / 10, row: rowNumber - 1 + Math.max(0, (55 - picture.height) / 42) / 2 }, ext: { width: picture.width, height: picture.height }, editAs: 'oneCell' })
    } else row.getCell(7).value = 'No signature'
  })
  if (!passengers.length) {
    sheet.mergeCells('A14:H14')
    sheet.getCell('A14').value = 'No boarded passengers recorded for this incoming trip.'
  }
  sheet.autoFilter = { from: 'A13', to: `H${Math.max(13, passengers.length + 13)}` }
  sheet.pageSetup.printArea = `A1:H${Math.max(14, passengers.length + 13)}`
  sheet.headerFooter.oddFooter = 'Trackline Incoming Manifest  •  Page &P of &N'
}

async function buildManifestWorkbook(records, generatedBy) {
  const workbook = new ExcelJS.Workbook()
  workbook.creator = `Main Gate - ${generatedBy}`
  workbook.created = new Date()
  const used = new Set()
  for (const record of records) manifestSheet(workbook, record.trip, record.passengers, generatedBy, used)
  if (!records.length) {
    const sheet = workbook.addWorksheet('No Incoming Trips')
    sheet.getCell('A1').value = 'No incoming shuttle trips found for this date.'
  }
  return workbook.xlsx.writeBuffer()
}

module.exports = { buildManifestWorkbook, uniqueSheetName, signatureImage }
